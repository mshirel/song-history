class TestFaviconRoute:
    """Browsers request /favicon.ico at the root, not under /static/."""

    def test_root_favicon_is_served(self, client) -> None:
        response = client.get("/favicon.ico")
        assert response.status_code == 200, (
            "the catch-all would otherwise answer /favicon.ico with a 404"
        )
        assert response.headers["content-type"] in (
            "image/vnd.microsoft.icon",
            "image/x-icon",
        )

    def test_root_favicon_answers_head(self, client) -> None:
        """Every GET route answers HEAD (#581)."""
        assert client.head("/favicon.ico").status_code == 200
